// Brand assets use authentic JetBrains Mono 2.304 Bold outlines, not live <text> or a substitute font.
import { GLYPHS } from "./glyphs.mjs";

export function brandSvg(flavor, { purpose = "avatar" } = {}) {
  if (!["avatar", "favicon"].includes(purpose)) throw new Error(`Unknown brand composition: ${purpose}`);
  const compact = purpose === "favicon";
  const size = compact ? 64 : 1024;
  const advance = compact ? 520 : 600;
  // Visible outline bounds, rather than the font's advance box: x = 185 .. (3 * advance + 415),
  // y = -110 .. 830. Centering these bounds gives equal visual margins on all four sides.
  const left = 185;
  const right = 3 * advance + 415;
  const width = compact ? 56 : size * 0.78;
  const scale = width / (right - left);
  const x = size / 2 - (left + right) / 2 * scale;
  const y = size / 2 + 360 * scale;
  const number = (n) => Number(n.toFixed(6));
  const paths = [..."[lc]"].map((glyph, index) => `    <path transform="translate(${index * advance} 0)" d="${GLYPHS[glyph]}"/>`).join("\n");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}" role="img" aria-labelledby="title">
  <title id="title">${compact ? flavor.name : "Living Code"}: [lc]</title>
  <desc>Living Code ${compact ? "favicon, optically spaced for small sizes" : "organization avatar, with circle-safe padding"}. JetBrains Mono 2.304 Bold glyph outlines, copyright 2020 The JetBrains Mono Project Authors, SIL Open Font License 1.1. Generated by scripts/build.mjs.</desc>
  <rect width="${size}" height="${size}"${compact ? ' rx="10"' : ""} fill="${flavor.c("base")}"/>
  <g fill="${flavor.c("teal")}" transform="translate(${number(x)} ${number(y)}) scale(${number(scale)} ${number(-scale)})">
${paths}
  </g>
</svg>
`;
}

export const brandFiles = (flavor) => [
  { path: "assets/brand/github-avatar.svg", content: brandSvg(flavor) },
  { path: "assets/brand/favicon.svg", content: brandSvg(flavor, { purpose: "favicon" }) },
];
